"""Build display permutations from frozen book-order evidence, never edit source text."""
import json,hashlib,heapq,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def read(p):return json.loads((root/p).read_text())
corpus=read('annotation-data/wolai-standard.json');old=read('annotation-data/chapters.json');evidence=read('annotation-data/reading-order-evidence.json')
oldc={c['id']:c for c in old['chapters']};legacy={p['page']:p for n in range(1,5) for p in read(f'annotation-data/part-{n}.json')['pages']}
pos=lambda page,offset:page*1000000+offset
for a in evidence['anchors']:
 p=legacy[a['page']];assert p['source']['textSha256']==a['textSha256'] and 0<=a['start']<a['end']<=len(p['text'].encode('utf-16-le'))//2
orders={};audit=[]
for c in corpus['index']['chapters']:
 for f in c['fragments']:
  p=next(p for p in corpus['pages'] if p['page']==f['page']);pro=p['source']['provenance'];ls=[i for i,m in enumerate(pro) if m['origin']=='legacy-reviewed-txt'];ws=[i for i,m in enumerate(pro) if m['origin'].startswith('wolai')]
  if not ls or not ws:continue
  edges=[set() for _ in pro];reasons=[];rejected=[]
  def edge(a,b,why):
   if a==b or b in edges[a]:return
   pending=[b];seen=set()
   while pending:
    n=pending.pop()
    if n==a:rejected.append([a,b,why]);return
    if n not in seen:seen.add(n);pending.extend(edges[n])
   edges[a].add(b);reasons.append([a,b,why])
  for seq in [ws,sorted(ls,key=lambda i:(pro[i]['page_id'],pro[i]['rawStart']))]:
   for a,b in zip(seq,seq[1:]):edge(a,b,'retained source sequence')
  anchors={}
  for i in ws:
   m=pro[i];bid='word-paragraph-'+m['id'].rsplit('-',1)[-1] if m['origin']=='wolai-word' else m['id']
   hits=[a for a in evidence['anchors'] if a['workId']==c['workId'] and bid in a['blocks'] and a['reference']==m['page_id'] and max(a['blocks'][bid][0],m['rawStart'])<min(a['blocks'][bid][1],m['rawEnd']) and any(x['page']==a['page'] and max(x['start'],a['start'])<min(x['end'],a['end']) for x in oldc.get(c['id'],{}).get('fragments',[]))]
   if hits:anchors[i]=(min(pos(a['page'],a['start']) for a in hits),max(pos(a['page'],a['end']) for a in hits),[a['id'] for a in hits])
  replaced=[r for r in evidence['replacements'] if r['chapterId']==c['id']]
  first=min((pos(r['page'],r['start']) for r in replaced),default=None);last=max((pos(r['page'],r['end']) for r in replaced),default=None)
  for i in ls:
   m=pro[i];a,z=pos(m['page_id'],m['rawStart']),pos(m['page_id'],m['rawEnd'])
   for j in ws:
    if first is not None and z<=first:edge(i,j,'before first replaced original block')
    elif last is not None and a>=last:edge(j,i,'after last replaced original block')
    elif j in anchors:
     lo,hi,_=anchors[j]
     if z<=lo:edge(i,j,'before comparison anchor')
     elif a>=hi:edge(j,i,'after comparison anchor')
  degree=[0]*len(pro)
  for es in edges:
   for j in es:degree[j]+=1
  ready=[i for i,d in enumerate(degree) if not d];heapq.heapify(ready);order=[]
  while ready:
   i=heapq.heappop(ready);order.append(i)
   for j in edges[i]:
    degree[j]-=1
    if not degree[j]:heapq.heappush(ready,j)
  conflict=len(order)!=len(pro)
  if conflict:order=list(range(len(pro)))
  changed=order!=list(range(len(pro)))
  # Keep each approved block and its following separator as an indivisible group.
  groups=[[b['start'] for b in f['blocks'] if m['start']<=b['start']<(pro[i+1]['start'] if i+1<len(pro) else f['end'])] for i,m in enumerate(pro)]
  if changed:orders[str(p['page'])]={'sha256':f['textSha256'],'starts':[start for i in order for start in groups[i]]}
  audit.append({'chapter':c['id'],'title':c['title'],'page':p['page'],'changed':changed,'conflict':conflict,'order':[pro[i]['id'] for i in order],'anchors':{str(i):v for i,v in anchors.items()},'constraints':reasons,'rejectedConstraints':rejected})
js='// Generated by scripts/build-reading-order.py; display only, original UTF-16 ranges stay fixed.\nexport const readingOrders='+json.dumps(orders,ensure_ascii=False,separators=(',',':'))+';\n'
path=root/'src/annotation-reading-orders.js'
if '--check' in sys.argv:assert path.read_text()==js,'Run python3 scripts/build-reading-order.py'
else:path.write_text(js)
if '--audit' in sys.argv:
 (root.parent.parent/'2026-10-28-reading-order-restoration/order-audit.json').write_text(json.dumps(audit,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'mixed':len(audit),'reordered':len(orders),'conflicts':[a['chapter'] for a in audit if a['conflict']],'partialEvidence':[a['chapter'] for a in audit if a['rejectedConstraints']]}))
