import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:8796';
const output = path.resolve(process.env.OUTPUT_DIR || '../../../tasks/2026-10-09-collation-interactions');
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [], errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
const key = 'shulun-screening-v1-part-1';
const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
const ready = async target => {
  await target.waitForSelector('#collationText');
  await target.waitForFunction(() => document.querySelector('#scanWrap img')?.naturalWidth > 0);
};
const openEditor = async target => {
  if (!(await target.locator('#editText').count())) await target.locator('#openTextEditor').click();
  await target.waitForSelector('#editText');
};
const go = async url => { await page.goto(`${base}/${url}`, { waitUntil: 'networkidle' }); await ready(page); };
const check = (name, value) => { assert.ok(value, name); results.push(name); };
try {
  await go('screening.html?part=1&page=154');
  await page.locator('#verifyNext').click();
  check('missing name blocks verification and focuses name', await page.locator('#person').evaluate(el => el === document.activeElement));
  await page.locator('#person').fill('交互验收测试');
  await openEditor(page);
  const original = await page.locator('#editText').inputValue();
  await page.locator('#editText').fill(original + '【待核：测试】');
  await page.locator('#verifyNext').click();
  check('unresolved text blocks verification', page.url().includes('page=154') && (await page.locator('#messageSlot').innerText()).includes('待核'));
  await page.locator('#editText').fill(original);
  await page.locator('#pageCheck').check();
  await page.locator('#renumber').click();
  check('no-op renumber preserves human checks', (await read()).reviews[154].collation.checks.wording === true);
  await page.locator('#verifyNext').click();
  await ready(page);
  check('verify saves and advances to pending page', page.url().includes('page=155') && (await read()).reviews[154].collation.verified);
  check('save success is visible', (await page.locator('#saveStatus').innerText()).includes('已自动保存'));
  await page.locator('#prev').click();
  await ready(page);
  await openEditor(page);
  await page.locator('#editText').fill(original + '。');
  check('real edit invalidates verification', !(await read()).reviews[154].collation.verified && (await read()).reviews[154].collation.checks.wording === undefined);
  check('existing controls retained without added filter or export panel', await page.locator('#pageFilter, #openExport, #exportDialog').count() === 0);
  await page.locator('.secondary-review summary').click();
  await page.locator('[name=quote]').fill('候选未提交草稿');
  await page.locator('#next').click(); await ready(page);
  await page.locator('#prev').click(); await ready(page);
  check('unsubmitted candidate input survives page navigation', await page.locator('[name=quote]').inputValue() === '候选未提交草稿');
  await page.locator('.topbar a').click();
  await page.waitForSelector('[data-continue-part="1"]');
  check('overview names the resume page', (await page.locator('[data-continue-part="1"]').innerText()).includes('154'));
  await page.locator('[data-continue-part="1"]').click(); await ready(page);
  check('overview resumes the same page', page.url().includes('page=154'));
  await page.reload({ waitUntil: 'networkidle' }); await ready(page);
  await openEditor(page);
  check('reload restores edited text', await page.locator('#editText').inputValue() === original + '。');
  await page.locator('.extra-tools > summary').click();
  for (const [selector, file, content] of [['#exportTxt','test-export.txt','状态：草稿'],['#exportChecks','test-checks.csv','校勘状态'],['#backup','test-backup.json','候选未提交草稿']]) {
    const promise = page.waitForEvent('download'); await page.locator(selector).click();
    const download = await promise; await download.saveAs(path.join(output,file));
    check(`actual ${file} download contains saved content`, (await fs.readFile(path.join(output,file),'utf8')).includes(content));
  }
  check('download summary uses the existing message area', (await page.locator('#messageSlot').innerText()).includes('备份下载'));
  await page.locator('.extra-tools > summary').click();
  await page.screenshot({ path: path.join(output,'existing-controls.png') });
  await page.evaluate(() => {
    window.originalStorageSet = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) { if (key.startsWith('shulun-screening')) throw new DOMException('Full','QuotaExceededError'); return window.originalStorageSet.call(this,key,value); };
  });
  await page.locator('#question').fill('未保存的疑问');
  await page.locator('#next').click();
  check('failed save keeps page and persistent warning', page.url().includes('page=154') && (await page.locator('#saveRecovery').innerText()).includes('保存失败'));
  await page.evaluate(() => { Storage.prototype.setItem = window.originalStorageSet; });
  await page.locator('#retrySave').click();
  check('retry saves the retained edit', (await read()).reviews[154].question === '未保存的疑问' && await page.locator('#saveRecovery').innerText() === '');
  const other = await context.newPage();
  await other.goto(`${base}/screening.html?part=1&page=154`,{waitUntil:'networkidle'}); await ready(other);
  await page.locator('#question').fill('标签 A 最新修改');
  await other.waitForSelector('#reloadProgress');
  await other.locator('#question').fill('标签 B 未保存修改');
  check('stale tab cannot overwrite newer progress', (await read()).reviews[154].question === '标签 A 最新修改');
  const rescuePromise = other.waitForEvent('download'); await other.locator('#rescueBackup').click();
  const rescue = await rescuePromise; await rescue.saveAs(path.join(output,'conflict-backup.json'));
  check('conflict backup includes unsaved text', (await fs.readFile(path.join(output,'conflict-backup.json'),'utf8')).includes('标签 B 未保存修改'));
  other.once('dialog', dialog => dialog.accept()); await other.locator('#reloadProgress').click();
  check('explicit reload restores newer stored progress', await other.locator('#question').inputValue() === '标签 A 最新修改');
  await other.close();
  await page.evaluate(() => window.scrollTo(0,0));
  for (const [width, height] of [[1440,900],[1280,720],[1024,600],[694,800],[390,844],[390,667]]) {
    await page.setViewportSize({width,height});
    await page.screenshot({path:path.join(output,`workspace-${width}x${height}.png`),fullPage:true});
    check(`no horizontal overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    check(`save status visible at ${width}px`, await page.locator('#saveStatus').isVisible());
    check(`document fits ${width}x${height} without vertical scrolling`, await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1 && document.body.scrollHeight <= innerHeight + 1 && scrollY === 0));
    check(`source, editor and actions remain inside ${width}x${height}`, await page.evaluate(() => ['#scanWrap','#collationText','#prev','#next','#verifyNext','#exportTxt'].every(selector => { const r=document.querySelector(selector).getBoundingClientRect(); return r.height >= 24 && r.width > 0 && r.top >= 0 && r.bottom <= innerHeight && r.right <= innerWidth; })));
    await page.locator('#zoom').selectOption('200');
    await page.locator('#scanWrap').hover(); await page.mouse.wheel(0,500);
    await page.waitForFunction(() => document.querySelector('#scanWrap').scrollTop > 0);
    check(`scan scroll stays inside the panel at ${width}px`, await page.evaluate(() => scrollY === 0));
    await openEditor(page); await page.locator('#editText').focus(); await page.keyboard.press('ControlOrMeta+End');
    check(`editor scroll keeps actions visible at ${width}px`, await page.evaluate(() => {const r=document.querySelector('#verifyNext').getBoundingClientRect(); return scrollY === 0 && r.bottom <= innerHeight;}));
    await page.locator('#zoom').selectOption('100');
    await page.locator('.extra-tools > summary').click();
    await page.locator('.local-fallback > summary').click();
    check(`expanded backup tools stay within ${width}x${height}`, await page.evaluate(() => { const r=document.querySelector('.extra-tools > .tools').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight && document.documentElement.scrollHeight <= innerHeight + 1; }));
    await page.locator('.local-fallback > summary').click();
    await page.locator('.extra-tools > summary').click();
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#next').click(); await ready(page);
  await page.locator('.extra-tools > summary').click();
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#backupFile').setInputFiles(path.join(output,'test-backup.json'));
  await page.waitForFunction(() => document.querySelector('#messageSlot')?.textContent.includes('进度备份已导入'));
  check('backup import restores saved location and candidate draft', page.url().includes('page=154') && (await read()).reviews[154].candidateDraft.quote === '候选未提交草稿');
  await page.locator('#next').click(); await ready(page);
  await page.locator('#collationText').focus();
  await page.keyboard.press('Alt+ArrowLeft'); await ready(page);
  check('keyboard page navigation preserves source and text page agreement', page.url().includes('page=154') && (await page.locator('#editorHeading').innerText()).includes('154'));
  // Small synthetic page set for end-of-queue behavior, separate from real-source tests.
  const fixture = await browser.newContext();
  const q = await fixture.newPage();
  await q.route('**/screening-data/part-2.json', route => route.fulfill({json:{part:2,start:259,end:261,pages:[259,260,261].map((page,i)=>({page,local:i+1}))}}));
  await q.route('**/screening-data/part-2-ocr.txt', route => route.fulfill({body:[259,260,261].map((page,i)=>`===== 原 PDF 物理页 ${page}｜分册第 ${i+1} 页 =====\n测试文字`).join('\n')}));
  await q.route('**/screening-data/part-2-layout.json', route => route.fulfill({status:404,body:''}));
  await q.goto(`${base}/screening.html?part=2&page=261`,{waitUntil:'networkidle'}); await ready(q);
  await q.locator('#person').fill('合成队列测试');
  for (const number of [261,259,260]) {
    await q.locator('#pageCheck').check();
    await q.locator('#verifyNext').click();
    if (number !== 260) await ready(q);
  }
  check('last-page completion reports success in the existing message area', (await q.locator('#messageSlot').innerText()).includes('本份全部校验完成') && await q.locator('#exportDialog').count() === 0);
  await fixture.close();
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output,'browser-results.json'),JSON.stringify({results,errors},null,2));
  console.log(`${results.length} browser assertions passed; screenshots and downloaded test files: ${output}`);
} finally { await browser.close(); }
